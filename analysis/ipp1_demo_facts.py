"""Numbers quoted in the live demo, computed from the local viewer data (never from hand-typed values).

    VIEWER_DATA=<path to viewer/data.js> python -I analysis/ipp1_demo_facts.py

Writes results/ipp1-demo-facts.md (aggregate numbers only). The viewer keeps every third row of each discharge,
so means here can differ slightly from means over all rows; all-row means need the raw data and are not computed.
Axis error is sqrt(dR^2+dZ^2) in mm per row, averaged per discharge (not the R-axis MAE of the slide).
"""
import json
import os
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[1]
SRC = Path(os.environ.get("VIEWER_DATA", REPO / "viewer/data.js"))
t = SRC.read_text()
D = json.loads(t[t.index("{"):t.rindex("}") + 1])
byid = {d["id"]: d for d in D["discharges"]}


def a(c, k):
    return np.array([np.nan if v is None else v for v in c[k]], float)


def dist(c, rk, zk, suffix="_pred"):
    return np.hypot(a(c, rk + suffix) - a(c, rk), a(c, zk + suffix) - a(c, zk)) * 1000


def at(d, tq):
    tt = a(d["c"], "time")
    return int(np.nanargmin(np.abs(tt - tq)))


def mean_axis(d, suffix="_pred"):
    return float(np.nanmean(dist(d["c"], "R_mag_axis", "Z_mag_axis", suffix)))


mean_all = {i: mean_axis(d) for i, d in byid.items()}
locked = [d["id"] for d in D["discharges"] if d["locked"]]
lm = sorted(((mean_all[i], i) for i in locked))
L = []
w = L.append
w("# Demo facts computed from the viewer data")
w("")
w(f"Generated by `analysis/ipp1_demo_facts.py` from `viewer/data.js` ({D['generated']}, model: {D['model']}, every {D['step']}rd row of each discharge). Aggregate numbers only; no raw rows.")
w("Axis error here is sqrt(dR^2+dZ^2) per row in mm, averaged per discharge. It is not the 0.133 mm R-axis MAE of the slide, which is a different quantity (R only, all rows, five folds). Values over every third row can differ from all-row means; all-row means need the raw data and are not computed here.")
w("")
w("## Moments of the live demo")
w("| Moment | Discharge | Frame time | Values |")
w("|---|---|---|---|")
d = byid[85]; c = d["c"]
i0 = at(d, 0.028); i1 = at(d, 0.502); i2 = at(d, 0.447)
ax = dist(c, "R_mag_axis", "Z_mag_axis"); lim = dist(c, "R_limiter", "Z_limiter"); xp = dist(c, "R_x_point", "Z_x_point")
w(f"| start (limited) | 85 | {a(c, 'time')[i0]:.3f} | axis error {ax[i0]:.2f} mm, limiter point {lim[i0]:.1f} mm |")
w(f"| middle (diverted) | 85 | {a(c, 'time')[i1]:.3f} | axis {ax[i1]:.2f} mm, X point {xp[i1]:.1f} mm |")
d147 = byid[147]; c7 = d147["c"]; ax7 = dist(c7, "R_mag_axis", "Z_mag_axis"); lim7 = dist(c7, "R_limiter", "Z_limiter"); il = int(np.where(np.isfinite(ax7))[0][-1])
w(f"| rough end | 147 | {a(c7, 'time')[il]:.3f} (last frame) | axis {ax7[il]:.1f} mm, limiter point {lim7[il]:.1f} mm; discharge mean {mean_all[147]:.2f} mm over the viewer rows |")
cl = dist(c, "R_mag_axis", "Z_mag_axis", "_clean_on_noisy"); hd = dist(c, "R_mag_axis", "Z_mag_axis", "_hardened_on_noisy")
w(f"| noise switch | 85 | {a(c, 'time')[i2]:.3f} | model trained on clean data {cl[i2]:.1f} mm axis error, noise-trained {hd[i2]:.2f} mm (discharge means {mean_axis(d, '_clean_on_noisy'):.1f} and {mean_axis(d, '_hardened_on_noisy'):.2f} mm) |")
w("")
w(f"The viewer's last-frame limiter value of discharge 147 is {lim7[il]:.1f} mm (error of the limiter point in that frame). The 105.7 in `results/ipp1-distribution.md` is a different quantity: the edge between plasma current quintiles Q4 and Q5 in kA.")
w("")
med = float(np.median([m for m, _ in lm]))
lower_med = lm[(len(lm) - 1) // 2]
w("## Typical discharge")
w(f"Discharge 85: mean axis error {mean_all[85]:.2f} mm, {byid[85]['n']} frames, {byid[85]['limitedShare'] * 100:.0f} % limited rows. Median of the mean axis error over the {len(locked)} set-aside discharges: {med:.2f} mm; the lower median is discharge {lower_med[1]} with {lower_med[0]:.2f} mm.")
w("")
w("## Aggregates")
w(f"- Set-aside discharges ({len(locked)}): all below 1 mm: {all(m < 1 for m, _ in lm)}; median {med:.2f} mm; worst id {lm[-1][1]} with {lm[-1][0]:.2f} mm, then {lm[-2][1]} with {lm[-2][0]:.2f} mm; any above 5 mm: {any(m > 5 for m, _ in lm)}.")
allm = sorted(((m, i) for i, m in mean_all.items()))
below1 = sum(1 for m, _ in allm if m < 1); above5 = [(i, m) for m, i in allm if m > 5]
w(f"- All {len(allm)} discharges (set-aside plus out-of-fold development discharges, same recipe): {below1} below 1 mm, {len(above5)} above 5 mm (" + ", ".join(f"id {i} with {m:.2f} mm" + (" set-aside" if i in locked else " development") for i, m in sorted(above5, key=lambda x: -x[1])) + ").")
w(f"- Worst three overall: " + ", ".join(f"id {i} {m:.2f} mm" for m, i in allm[::-1][:3]) + ".")
(REPO / "results/ipp1-demo-facts.md").write_text("\n".join(L) + "\n")
print("\n".join(L))
